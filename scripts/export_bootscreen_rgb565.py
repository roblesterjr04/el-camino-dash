#!/usr/bin/env python3
"""Embed assets/bootscreen/boot3.png as RGB565 for ESP32-P4 direct framebuffer boot splash.

Generates one header per panel size (contain scaling, letterboxed on black):
  - bootscreen_rgb565_800_gen.h   — 800×800 (Waveshare 3.4C / center + speedo on that panel)
  - bootscreen_rgb565_720_gen.h   — 720×720 (typical left/right JD9365 / JD9165 square kits)
  - bootscreen_rgb565_1024x600_gen.h — 1024×600 (EV7\" stock kit), optional
"""

from __future__ import annotations

import argparse
import pathlib
import sys

try:
    from PIL import Image
except ImportError as e:  # pragma: no cover
    raise SystemExit("Install Pillow: pip install pillow") from e

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEFAULT_PNG = ROOT / "assets" / "bootscreen" / "boot3.png"
DEFAULT_OUT_DIR = ROOT / "firmware" / "esp32_p4_common" / "include"

PRESETS: list[tuple[int, int, str]] = [
    (800, 800, "bootscreen_rgb565_800_gen.h"),
    (720, 720, "bootscreen_rgb565_720_gen.h"),
    (1024, 600, "bootscreen_rgb565_1024x600_gen.h"),
]


def rgb888_to_rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def export_contain(src_im: Image.Image, ow: int, oh: int, fh) -> None:
    iw, ih = src_im.size
    if iw <= 0 or ih <= 0:
        raise SystemExit("invalid source image size")

    scale = min(ow / iw, oh / ih)
    nw = max(1, int(iw * scale))
    nh = max(1, int(ih * scale))
    resized = src_im.resize((nw, nh), Image.Resampling.LANCZOS)

    canvas = Image.new("RGBA", (ow, oh), (0, 0, 0, 255))
    ox = (ow - nw) // 2
    oy = (oh - nh) // 2
    canvas.paste(resized, (ox, oy), resized)

    fh.write(f"#define ELC_BOOT_SPLASH_W {ow}\n")
    fh.write(f"#define ELC_BOOT_SPLASH_H {oh}\n\n")
    fh.write("static const uint16_t elc_boot_splash_rgb565[] PROGMEM = {\n")

    words: list[int] = []
    for y in range(oh):
        for x in range(ow):
            px = canvas.getpixel((x, y))
            r, g, b = px[0], px[1], px[2]
            words.append(rgb888_to_rgb565(r, g, b))

    per_line = 8
    for i in range(0, len(words), per_line):
        chunk = words[i : i + per_line]
        fh.write("  " + ", ".join(f"0x{w:04X}" for w in chunk))
        fh.write(",\n" if i + per_line < len(words) else "")
    fh.write("};\n")


def write_one(src: pathlib.Path, out_dir: pathlib.Path, ow: int, oh: int, out_name: str) -> pathlib.Path:
    im = Image.open(src).convert("RGBA")
    out_path = out_dir / out_name
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as fh:
        fh.write("/* Auto-generated by scripts/export_bootscreen_rgb565.py — do not edit */\n")
        fh.write("#pragma once\n\n")
        fh.write("#include <stdint.h>\n\n")
        export_contain(im, ow, oh, fh)
    return out_path


def main() -> int:
    ap = argparse.ArgumentParser(description="RGB565 headers for boot splash (contain scale per panel size).")
    ap.add_argument("--src", type=pathlib.Path, default=DEFAULT_PNG, help="Source PNG")
    ap.add_argument(
        "--out-dir",
        type=pathlib.Path,
        default=DEFAULT_OUT_DIR,
        help=f"Output directory (default: {DEFAULT_OUT_DIR})",
    )
    args = ap.parse_args()
    if not args.src.is_file():
        raise SystemExit(f"Missing {args.src}")

    written: list[pathlib.Path] = []
    for ow, oh, name in PRESETS:
        written.append(write_one(args.src, args.out_dir, ow, oh, name))
    for p in written:
        print(f"Wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
