#!/usr/bin/env python3
"""
Generate C headers with RGB565 + alpha arrays for the classic_2 TSPS cluster
(full_gauges.png + full_guage_mask.png), scaled for embedded use.

Requires Pillow (see project venv: python3 -m venv .venv-assets && pip install pillow).

Usage:
  python3 scripts/export_tsps_rgb565_assets.py [output_dir] [--edge N]

  --edge  — square size in pixels (default 480 for Waveshare 3.4C / 800² MIPI). Use --edge 360 to save RAM on 720²-only builds.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

try:
    from PIL import Image
except ImportError as e:  # pragma: no cover
    raise SystemExit("Install Pillow: pip install pillow") from e

ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "assets" / "gauges" / "classic_2_rect"

# Match themes/classic_2 theme.json sprite_overrides.tsps + sprite_render.tsps
DIAL_FILE = "full_gauges.png"
MASK_FILE = "full_guage_mask.png"

# Default export edge: 480 fits 800×800 round MIPI (Waveshare 3.4C); 360 is smaller for RAM-tight builds.
DEFAULT_TARGET_EDGE = 480


def rgb888_to_rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def export_layer(im: Image.Image, name: str, fh) -> None:
    w, h = im.size
    fh.write(f"// {name} {w}x{h} RGB565 + alpha8\n")
    fh.write(f"static const uint16_t tsps_{name}_rgb565[] PROGMEM = {{\n")
    words: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            if len(px) == 4:
                r, g, b, a = px
            else:
                r, g, b = px
                a = 255
            words.append(rgb888_to_rgb565(r, g, b))
    _write_u16_chunks(words, fh)
    fh.write("};\n\n")

    fh.write(f"static const uint8_t tsps_{name}_alpha[] PROGMEM = {{\n")
    alphas: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            a = px[3] if len(px) == 4 else 255
            alphas.append(a)
    _write_u8_chunks(alphas, fh)
    fh.write("};\n\n")


def _write_u16_chunks(words: list[int], fh, per_line: int = 12) -> None:
    for i in range(0, len(words), per_line):
        chunk = words[i : i + per_line]
        fh.write("  " + ", ".join(f"0x{w:04X}" for w in chunk))
        fh.write(",\n" if i + per_line < len(words) else "")


def _write_u8_chunks(vals: list[int], fh, per_line: int = 16) -> None:
    for i in range(0, len(vals), per_line):
        chunk = vals[i : i + per_line]
        fh.write("  " + ", ".join(f"0x{v:02X}" for v in chunk))
        fh.write(",\n" if i + per_line < len(vals) else "")


def main() -> None:
    ap = argparse.ArgumentParser(description="Export TSPS cluster RGB565 assets for ESP32-P4 firmware.")
    ap.add_argument(
        "out_dir",
        nargs="?",
        type=pathlib.Path,
        default=ROOT / "firmware" / "esp32_p4_tsps" / "src",
        help="Directory for tsps_assets_gen.h (default: firmware/esp32_p4_tsps/src)",
    )
    ap.add_argument(
        "--edge",
        type=int,
        default=DEFAULT_TARGET_EDGE,
        metavar="N",
        help=f"Output square size (default {DEFAULT_TARGET_EDGE}; use 360 for minimal PSRAM)",
    )
    args = ap.parse_args()
    target_edge = args.edge
    if target_edge < 120 or target_edge > 1080:
        raise SystemExit("--edge must be between 120 and 1080")

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    out_h = out_dir / "tsps_assets_gen.h"

    dial_path = ASSET_DIR / DIAL_FILE
    mask_path = ASSET_DIR / MASK_FILE
    if not dial_path.is_file() or not mask_path.is_file():
        raise SystemExit(f"Missing assets under {ASSET_DIR}")

    dial = Image.open(dial_path).convert("RGBA")
    mask = Image.open(mask_path).convert("RGBA")
    dial = dial.resize((target_edge, target_edge), Image.Resampling.LANCZOS)
    mask = mask.resize((target_edge, target_edge), Image.Resampling.LANCZOS)

    with out_h.open("w", encoding="utf-8") as fh:
        fh.write(
            "/* Auto-generated by scripts/export_tsps_rgb565_assets.py — do not edit */\n"
            "#pragma once\n"
            "#include <Arduino.h>\n"
            "#include <stdint.h>\n\n"
        )
        fh.write(f"#define TSPS_ASSET_EDGE {target_edge}\n\n")
        export_layer(dial, "dial", fh)
        export_layer(mask, "overlay", fh)

    print(f"Wrote {out_h} ({out_h.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
