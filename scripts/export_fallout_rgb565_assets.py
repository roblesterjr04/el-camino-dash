#!/usr/bin/env python3
"""Optional Fallout PNG → RGB565 headers for ESP32-P4 gauges.

Reads every *.png under assets/gauges/fallout/, scales to --edge square (default 480),
and writes a single generated header with PROGMEM arrays.

If no PNGs are present, writes a stub with FALLOUT_ASSETS_HAVE 0 so firmware can
#include the file unconditionally once wired up.
"""

from __future__ import annotations

import argparse
import pathlib
import re

try:
    from PIL import Image
except ImportError as e:  # pragma: no cover
    raise SystemExit("Install Pillow: pip install pillow") from e

ROOT = pathlib.Path(__file__).resolve().parents[1]
FALLOUT_DIR = ROOT / "assets" / "gauges" / "fallout"


def rgb888_to_rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def safe_sym(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]+", "_", name)
    if s and s[0].isdigit():
        s = "_" + s
    return s or "asset"


def export_layer(im: Image.Image, fh, array_base: str) -> None:
    w, h = im.size
    fh.write(f"// {array_base} {w}x{h} RGB565 + alpha8\n")
    fh.write(f"static const uint16_t {array_base}_rgb565[] PROGMEM = {{\n")
    words: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            if len(px) == 4:
                r, g, b, _a = px
            else:
                r, g, b = px
            words.append(rgb888_to_rgb565(r, g, b))
    per_line = 12
    for i in range(0, len(words), per_line):
        chunk = words[i : i + per_line]
        fh.write("  " + ", ".join(f"0x{w:04X}" for w in chunk))
        fh.write(",\n" if i + per_line < len(words) else "")
    fh.write("};\n\n")

    fh.write(f"static const uint8_t {array_base}_alpha[] PROGMEM = {{\n")
    alphas: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            alphas.append(px[3] if len(px) == 4 else 255)
    for i in range(0, len(alphas), 16):
        chunk = alphas[i : i + 16]
        fh.write("  " + ", ".join(f"0x{v:02X}" for v in chunk))
        fh.write(",\n" if i + 16 < len(alphas) else "")
    fh.write("};\n\n")


def write_stub(path: pathlib.Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        fh.write(
            "/* Auto-generated by scripts/export_fallout_rgb565_assets.py — no PNGs in assets/gauges/fallout */\n"
            "#pragma once\n#include <Arduino.h>\n#include <stdint.h>\n\n"
            "#define FALLOUT_ASSETS_HAVE 0\n"
        )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "out_dir",
        nargs="?",
        type=pathlib.Path,
        default=ROOT / "firmware" / "esp32_p4_center" / "src",
    )
    ap.add_argument("--edge", type=int, default=480)
    args = ap.parse_args()
    edge = args.edge
    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    out_h = out_dir / "fallout_assets_gen.h"

    FALLOUT_DIR.mkdir(parents=True, exist_ok=True)
    pngs = sorted(FALLOUT_DIR.glob("*.png"))
    if not pngs:
        write_stub(out_h)
        print(f"No PNGs in {FALLOUT_DIR}; wrote stub {out_h}")
        return

    with out_h.open("w", encoding="utf-8") as fh:
        fh.write(
            "/* Auto-generated by scripts/export_fallout_rgb565_assets.py */\n"
            "#pragma once\n#include <Arduino.h>\n#include <stdint.h>\n\n"
            f"#define FALLOUT_ASSETS_HAVE 1\n#define FALLOUT_ASSET_EDGE {edge}\n\n"
        )
        for p in pngs:
            base = safe_sym(p.stem.lower())
            im = Image.open(p).convert("RGBA").resize((edge, edge), Image.Resampling.LANCZOS)
            fh.write(f"#define FALLOUT_{base.upper()}_W {edge}\n")
            fh.write(f"#define FALLOUT_{base.upper()}_H {edge}\n")
            export_layer(im, fh, f"fallout_{base}")

    print(f"Wrote {out_h} ({len(pngs)} layer(s))")


if __name__ == "__main__":
    main()
