#!/usr/bin/env python3
"""Generate tsps_classic1_assets_gen.h from classic_1_rect TSPS sprites (indicator_fuel + gauge_mask)."""

from __future__ import annotations

import argparse
import pathlib
import sys

try:
    from PIL import Image
except ImportError as e:  # pragma: no cover
    raise SystemExit("Install Pillow: pip install pillow") from e

ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "assets" / "gauges" / "classic_1_rect"
DIAL_FILE = "indicator_fuel.png"
MASK_FILE = "gauge_mask.png"

DEFAULT_TARGET_EDGE = 480


def rgb888_to_rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def export_layer(im: Image.Image, name: str, fh) -> None:
    w, h = im.size
    fh.write(f"// {name} {w}x{h} RGB565 + alpha8\n")
    fh.write(f"static const uint16_t tsps_c1_{name}_rgb565[] PROGMEM = {{\n")
    words: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            if len(px) == 4:
                r, g, b, _a = px
            else:
                r, g, b = px
            words.append(rgb888_to_rgb565(r, g, b))
    per_line = 12
    for i in range(0, len(words), per_line):
        chunk = words[i : i + per_line]
        fh.write("  " + ", ".join(f"0x{w:04X}" for w in chunk))
        fh.write(",\n" if i + per_line < len(words) else "")
    fh.write("};\n\n")

    fh.write(f"static const uint8_t tsps_c1_{name}_alpha[] PROGMEM = {{\n")
    alphas: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            a = px[3] if len(px) == 4 else 255
            alphas.append(a)
    for i in range(0, len(alphas), 16):
        chunk = alphas[i : i + 16]
        fh.write("  " + ", ".join(f"0x{v:02X}" for v in chunk))
        fh.write(",\n" if i + 16 < len(alphas) else "")
    fh.write("};\n\n")


def main() -> None:
    ap = argparse.ArgumentParser(description="Export classic_1 TSPS RGB565 assets for ESP32-P4.")
    ap.add_argument(
        "out_dir",
        nargs="?",
        type=pathlib.Path,
        default=ROOT / "firmware" / "esp32_p4_tsps" / "src",
        help="Output directory for tsps_classic1_assets_gen.h",
    )
    ap.add_argument("--edge", type=int, default=DEFAULT_TARGET_EDGE, help="Square edge (default 480; use 360 for 720² boards)")
    args = ap.parse_args()
    edge = args.edge
    if edge < 120 or edge > 1080:
        raise SystemExit("--edge must be between 120 and 1080")

    dial_path = ASSET_DIR / DIAL_FILE
    mask_path = ASSET_DIR / MASK_FILE
    if not dial_path.is_file() or not mask_path.is_file():
        raise SystemExit(f"Missing {DIAL_FILE} or {MASK_FILE} under {ASSET_DIR}")

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    out_h = out_dir / "tsps_classic1_assets_gen.h"

    dial = Image.open(dial_path).convert("RGBA")
    mask = Image.open(mask_path).convert("RGBA")
    dial = dial.resize((edge, edge), Image.Resampling.LANCZOS)
    mask = mask.resize((edge, edge), Image.Resampling.LANCZOS)

    with out_h.open("w", encoding="utf-8") as fh:
        fh.write(
            "/* Auto-generated by scripts/export_tsps_classic1_rgb565_assets.py — do not edit */\n"
            "#pragma once\n"
            "#include <Arduino.h>\n"
            "#include <stdint.h>\n\n"
        )
        fh.write(f"#define TSPS_C1_ASSET_EDGE {edge}\n\n")
        export_layer(dial, "dial", fh)
        export_layer(mask, "overlay", fh)

    print(f"Wrote {out_h} ({out_h.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
