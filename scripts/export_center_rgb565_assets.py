#!/usr/bin/env python3
"""Tach dial + optional clock sprites for center gauge.

Outputs:
  - firmware/esp32_p4_center/src/center_assets_gen.h  (requires tach_base.png)
  - firmware/esp32_p4_center/src/center_clock_assets_gen.h (optional PNGs)

Search order for each PNG (first match wins):
  1. assets/gauges/classic_1/  (classic_1 clock quadrant, silver dial, needle, tach)
  2. assets/gauges/classic_2_rect/
  3. themes/classic_2/

Required: tach_base.png somewhere in the search path.
Optional clock bundle: needle.png, clock-dial-cover.png, clock-face.png

When optional files are missing, center_clock_assets_gen.h is written with *_HAVE 0 so
firmware falls back to line clock hands and no dial/overlay.
"""

from __future__ import annotations

import argparse
import pathlib

try:
    from PIL import Image
except ImportError as e:  # pragma: no cover
    raise SystemExit("Install Pillow: pip install pillow") from e

ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSET_CLASSIC1 = ROOT / "assets" / "gauges" / "classic_1"
ASSET_DIR = ROOT / "assets" / "gauges" / "classic_2_rect"
THEME_CLASSIC2 = ROOT / "themes" / "classic_2"
DIAL_FILE = "tach_base.png"
NEEDLE_FILE = "needle.png"
CLOCK_DIAL_FILE = "clock-dial-cover.png"
CLOCK_FACE_FILE = "clock-face.png"
DEFAULT_EDGE = 480

# classic_1 first so clock-face / clock-dial-cover / needle match the HDMI classic_1 theme.
SEARCH_DIRS = (
    ASSET_CLASSIC1,
    ASSET_DIR,
    THEME_CLASSIC2,
)


def resolve_png(name: str) -> pathlib.Path | None:
    for d in SEARCH_DIRS:
        p = d / name
        if p.is_file():
            return p
    return None


def rgb888_to_rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def export_layer(im: Image.Image, fh, array_base: str) -> None:
    w, h = im.size
    fh.write(f"// layer {w}x{h} RGB565 + alpha8\n")
    fh.write(f"static const uint16_t {array_base}_rgb565[] PROGMEM = {{\n")
    words: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            if len(px) == 4:
                r, g, b, _a = px
            else:
                r, g, b = px
            words.append(rgb888_to_rgb565(r, g, b))
    per_line = 12
    for i in range(0, len(words), per_line):
        chunk = words[i : i + per_line]
        fh.write("  " + ", ".join(f"0x{w:04X}" for w in chunk))
        fh.write(",\n" if i + per_line < len(words) else "")
    fh.write("};\n\n")

    fh.write(f"static const uint8_t {array_base}_alpha[] PROGMEM = {{\n")
    alphas: list[int] = []
    for y in range(h):
        for x in range(w):
            px = im.getpixel((x, y))
            alphas.append(px[3] if len(px) == 4 else 255)
    for i in range(0, len(alphas), 16):
        chunk = alphas[i : i + 16]
        fh.write("  " + ", ".join(f"0x{v:02X}" for v in chunk))
        fh.write(",\n" if i + 16 < len(alphas) else "")
    fh.write("};\n\n")


def scale_needle_like_pygame(needle_rgba: Image.Image, edge: int, scale: float) -> Image.Image:
    """Match gauge_screen._draw_clock_sprite_hand sizing (long side = min_dim * scale)."""
    w, h = needle_rgba.size
    if w <= 0 or h <= 0:
        raise ValueError("empty needle")
    target = max(6, int(edge * scale))
    if w >= h:
        new_w = target
        new_h = max(1, int((h / w) * target))
    else:
        new_h = target
        new_w = max(1, int((w / h) * target))
    return needle_rgba.resize((new_w, new_h), Image.Resampling.LANCZOS)


def write_clock_stub(fh) -> None:
    fh.write(
        """/* Optional clock assets not found — line hands + no dial/overlay at runtime. */
#define CENTER_CLOCK_DIAL_HAVE 0
#define CENTER_CLOCK_OVERLAY_HAVE 0
#define CENTER_CLOCK_NEEDLE_HOUR_W 0
#define CENTER_CLOCK_NEEDLE_HOUR_H 0
#define CENTER_CLOCK_NEEDLE_MINUTE_W 0
#define CENTER_CLOCK_NEEDLE_MINUTE_H 0
"""
    )


def export_clock_assets(out_h: pathlib.Path, edge: int) -> None:
    needle_p = resolve_png(NEEDLE_FILE)
    dial_p = resolve_png(CLOCK_DIAL_FILE)
    face_p = resolve_png(CLOCK_FACE_FILE)
    # Silver hub (clock-dial-cover): half the layout edge — full edge was oversized vs Pi layout.
    dial_edge = max(1, edge // 2)

    with out_h.open("w", encoding="utf-8") as fh:
        fh.write(
            "/* Auto-generated by scripts/export_center_rgb565_assets.py (clock section) */\n"
            "#pragma once\n#include <Arduino.h>\n#include <stdint.h>\n\n"
        )

        if needle_p is None:
            write_clock_stub(fh)
            return

        im_needle = Image.open(needle_p).convert("RGBA")
        hour_im = scale_needle_like_pygame(im_needle, edge, 0.30)
        min_im = scale_needle_like_pygame(im_needle, edge, 0.45)

        hw, hh = hour_im.size
        mw, mh = min_im.size
        dial_have = dial_p is not None
        face_have = face_p is not None

        fh.write(f"#define CENTER_CLOCK_NEEDLE_HOUR_W {hw}\n")
        fh.write(f"#define CENTER_CLOCK_NEEDLE_HOUR_H {hh}\n")
        fh.write(f"#define CENTER_CLOCK_NEEDLE_MINUTE_W {mw}\n")
        fh.write(f"#define CENTER_CLOCK_NEEDLE_MINUTE_H {mh}\n")
        fh.write(f"#define CENTER_CLOCK_DIAL_HAVE {1 if dial_have else 0}\n")
        fh.write(f"#define CENTER_CLOCK_OVERLAY_HAVE {1 if face_have else 0}\n")
        if dial_have:
            fh.write(f"#define CENTER_CLOCK_DIAL_W {dial_edge}\n#define CENTER_CLOCK_DIAL_H {dial_edge}\n")
        else:
            fh.write("#define CENTER_CLOCK_DIAL_W 0\n#define CENTER_CLOCK_DIAL_H 0\n")
        if face_have:
            fh.write(f"#define CENTER_CLOCK_OVERLAY_W {edge}\n#define CENTER_CLOCK_OVERLAY_H {edge}\n")
        else:
            fh.write("#define CENTER_CLOCK_OVERLAY_W 0\n#define CENTER_CLOCK_OVERLAY_H 0\n")
        fh.write("\n")

        export_layer(hour_im, fh, "center_clock_needle_hour")
        export_layer(min_im, fh, "center_clock_needle_minute")
        if dial_have:
            d_im = Image.open(dial_p).convert("RGBA").resize((dial_edge, dial_edge), Image.Resampling.LANCZOS)
            export_layer(d_im, fh, "center_clock_dial")
        if face_have:
            f_im = Image.open(face_p).convert("RGBA").resize((edge, edge), Image.Resampling.LANCZOS)
            export_layer(f_im, fh, "center_clock_overlay")


def export_tach_header(out_h: pathlib.Path, edge: int) -> None:
    p = resolve_png(DIAL_FILE)
    if p is None:
        raise SystemExit(
            f"Missing {DIAL_FILE} under {ASSET_DIR} or {THEME_CLASSIC2} "
            "(copy from your theme pack or sync assets/gauges/classic_2_rect)."
        )

    im = Image.open(p).convert("RGBA").resize((edge, edge), Image.Resampling.LANCZOS)
    with out_h.open("w", encoding="utf-8") as fh:
        fh.write(
            "/* Auto-generated by scripts/export_center_rgb565_assets.py */\n#pragma once\n#include <Arduino.h>\n#include <stdint.h>\n\n"
        )
        fh.write(f"#define CENTER_ASSET_EDGE {edge}\n\n")
        export_layer(im, fh, "center_tach_dial")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir", nargs="?", type=pathlib.Path, default=ROOT / "firmware" / "esp32_p4_center" / "src")
    ap.add_argument("--edge", type=int, default=DEFAULT_EDGE)
    args = ap.parse_args()
    edge = args.edge

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    tach_h = out_dir / "center_assets_gen.h"
    export_tach_header(tach_h, edge)
    print(f"Wrote {tach_h}")

    clock_h = out_dir / "center_clock_assets_gen.h"
    export_clock_assets(clock_h, edge)
    print(f"Wrote {clock_h}")


if __name__ == "__main__":
    main()
